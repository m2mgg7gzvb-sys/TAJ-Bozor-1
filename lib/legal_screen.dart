/// Экран юридического текста: заголовок и разделы на русском или таджикском.
class LegalPage extends StatelessWidget {
  const LegalPage({super.key, required this.title, required this.sections, required this.updated});

  final String title;
  final List<(String, String)> sections;
  final String updated;

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: Text(title)),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(20, 16, 20, 32),
        children: [
          Text(
            tr('Дата последнего изменения: $updated', 'Санаи охирин тағйирёбӣ: $updated'),
            style: const TextStyle(color: AppColors.muted, fontSize: 13),
          ),
          const SizedBox(height: 16),
          for (final (heading, body) in sections) ...[
            Text(heading, style: const TextStyle(fontWeight: FontWeight.w800, fontSize: 16)),
            const SizedBox(height: 6),
            Text(body, style: const TextStyle(height: 1.45)),
            const SizedBox(height: 18),
          ],
        ],
      ),
    );
  }
}

